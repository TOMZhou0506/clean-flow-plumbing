<?php
declare(strict_types=1);

namespace App\Controller;

use Cake\Core\Configure;
use Cake\Event\EventInterface;
use Cake\Http\Client;
use Throwable;

/**
 * Contacts Controller
 *
 * The public contact form. This is the only write path into the enquiry
 * dashboard, so the two have to agree on where the data lives.
 *
 * I changed two things here after finding the page was broken:
 *
 * 1. It saved through the Contacts model, which points at a `contacts` table
 *    that does not exist. There is no migration for it and it is not in
 *    Suhana's database dump either, so every submission died with
 *    "Base table or view not found: 1146". It now saves through
 *    ContactSubmissions, which is the table the dashboard actually reads.
 *    Before this change a submission could not have reached the dashboard
 *    even if the table had existed, because they were two different tables.
 * 2. The action required a login. AppController loads the Authentication
 *    component for every controller, and nothing here opted out, so a
 *    customer hit the admin login screen instead of the form.
 *
 * @property \App\Model\Table\ContactsTable $Contacts
 */
class ContactsController extends AppController
{
    /**
     * Lets the public reach the contact form.
     *
     * Only `add` is opened up. If anyone adds an action to this controller
     * later it stays behind the login until they list it here, which is the
     * fail-closed behaviour I wanted from AppController.
     *
     * @param \Cake\Event\EventInterface $event The beforeFilter event.
     * @return void
     */
    public function beforeFilter(EventInterface $event): void
    {
        parent::beforeFilter($event);

        $this->Authentication->addUnauthenticatedActions(['add']);
    }

    /**
     * Public contact form.
     *
     * @return \Cake\Http\Response|null|void Redirects after a successful save.
     */
    public function add()
    {
        // ContactSubmissions, not Contacts. See the note on the class above.
        $submissions = $this->fetchTable('ContactSubmissions');

        // I keep the view variable named $contact so the template does not
        // have to change beyond its docblock.
        $contact = $submissions->newEmptyEntity();
        $turnstileSiteKey = (string)Configure::read('Turnstile.siteKey', '');
        $turnstileSecretKey = (string)Configure::read('Turnstile.secretKey', '');

        // Only process data when the form is submitted using POST.
        if ($this->request->is('post')) {
            // Fail closed if deployment configuration is incomplete. In
            // particular, never accept a request merely because CAPTCHA
            // credentials were forgotten during deployment.
            if ($turnstileSiteKey === '' || $turnstileSecretKey === '') {
                $this->Flash->error(
                    'Human verification is temporarily unavailable. Please try again later.',
                );

                $this->set(compact('contact', 'turnstileSiteKey'));

                return;
            }

            // Get the Turnstile token generated by the CAPTCHA widget.
            $turnstileToken = (string)$this->request->getData('cf-turnstile-response', '');

            if ($turnstileToken === '') {
                $this->Flash->error('Please complete the human verification check.');
                $this->set(compact('contact', 'turnstileSiteKey'));

                return;
            }

            try {
                // Verification must happen on the server. A green widget in
                // the browser is not sufficient proof by itself.
                $response = (new Client())->post(
                    'https://challenges.cloudflare.com/turnstile/v0/siteverify',
                    [
                        'secret' => $turnstileSecretKey,
                        'response' => $turnstileToken,
                        'remoteip' => $this->request->clientIp(),
                    ],
                );
                $captchaResult = $response->getJson();
            } catch (Throwable) {
                // A Cloudflare/network outage must not bypass verification or
                // expose an exception page to a public visitor.
                $captchaResult = null;
            }

            // Stop the submission if CAPTCHA verification fails.
            if (!is_array($captchaResult) || empty($captchaResult['success'])) {
                $this->Flash->error(
                    'CAPTCHA verification failed. Please try again.',
                );

                $this->set(compact('contact'));

                return;
            }

            // Copy submitted form data into the entity.
            //
            // patchEntity only accepts the fields ContactSubmission marks as
            // accessible, so a crafted POST carrying status, read_at, read_by
            // or submitted_at cannot set them. That matters here more than
            // anywhere else in the app, because this is the one action a
            // stranger on the internet can reach.
            $contact = $submissions->patchEntity(
                $contact,
                $this->request->getData(),
            );

            // Save the contact submission if validation succeeds.
            if ($submissions->save($contact)) {
                $this->Flash->success(
                    'Thank you. Your message has been submitted successfully.',
                );

                return $this->redirect(['action' => 'add']);
            }

            // Show an error message if validation or saving fails.
            $this->Flash->error(
                'Your message could not be submitted. Please check the form and try again.',
            );
        }

        $this->set(compact('contact', 'turnstileSiteKey'));
    }
}
